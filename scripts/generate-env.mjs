// Writes src/environments/environment.generated.ts with RAZORPAY_KEY_ID taken from the process
// environment first, then from a .env file in the project root. The value is never printed.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const VARIABLE = 'RAZORPAY_KEY_ID';
// Razorpay key ids look like rzp_test_xxxxxxxx or rzp_live_xxxxxxxx. Anything else is rejected so a
// secret pasted by mistake can never be written into the JavaScript bundle.
const KEY_ID_PATTERN = /^rzp_(test|live)_[A-Za-z0-9]+$/;

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = resolve(root, '.env');
const baseFile = resolve(root, 'src/environments/environment.ts');
const outFile = resolve(root, 'src/environments/environment.generated.ts');

function readDotEnv(path) {
  const values = {};
  for (const rawLine of readFileSync(path, 'utf8').replace(/^﻿/, '').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) {
      continue;
    }
    const match = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!match) {
      continue;
    }
    let value = match[2].trim();
    const quote = value[0];
    if ((quote === '"' || quote === "'") && value.endsWith(quote) && value.length >= 2) {
      value = value.slice(1, -1);
    } else {
      value = value.replace(/\s+#.*$/, '');
    }
    values[match[1]] = value.trim();
  }
  return values;
}

let keyId = (process.env[VARIABLE] ?? '').trim();
let source = keyId ? 'process environment' : '';
if (!keyId && existsSync(envFile)) {
  keyId = (readDotEnv(envFile)[VARIABLE] ?? '').trim();
  source = keyId ? '.env file' : '';
}

if (keyId && !KEY_ID_PATTERN.test(keyId)) {
  console.error(
    `${VARIABLE} does not look like a Razorpay key id (expected rzp_test_... or rzp_live_...). ` +
      'Use the public key id, never the secret. Nothing was written.',
  );
  process.exit(1);
}

const apiBaseUrl = /apiBaseUrl:\s*'([^']*)'/.exec(readFileSync(baseFile, 'utf8'))?.[1];
if (apiBaseUrl === undefined) {
  console.error('Could not read apiBaseUrl from src/environments/environment.ts.');
  process.exit(1);
}

writeFileSync(
  outFile,
  `// Generated by scripts/generate-env.mjs. Do not edit or commit.
export const environment = {
  production: false,
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
  razorpayKeyId: ${JSON.stringify(keyId)},
};
`,
);

console.log(
  `environment.generated.ts written (${VARIABLE}: ${keyId ? `set from ${source}` : 'not set'}).`,
);
